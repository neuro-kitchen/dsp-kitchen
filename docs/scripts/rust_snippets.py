"""Every Rust block of the guides as compiled code: writes `crates/dspk/tests/doc_snippets.rs`, one
function per block, so `cargo check --all-targets` (CI) fails when a snippet stops compiling. Blocks
that are fragments get the variables they use from `PRELUDE`.

Run from the repository root (standard library only): python3 docs/scripts/rust_snippets.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "src" / "content" / "docs"
OUT = ROOT / "crates" / "dspk" / "tests" / "doc_snippets.rs"
PAGES = ["learn/get-started/first-filter.mdx", *sorted(p.relative_to(DOCS).as_posix() for p in (DOCS / "operations").glob("*.mdx"))]
PRELUDE = """\
    let client = dspk::core::compute::ComputeTarget::from_env()?.client()?;
    let (channels, samples, epsilon) = (4_usize, 1_000_usize, 1e-6_f32);
    let data = vec![0.0_f32; channels * samples];
    let taps = vec![0.2_f32; 5];
    let mut pipeline = Pipeline::new();
"""


def main() -> None:
    out = [
        "//! Generated by docs/scripts/rust_snippets.py from the guides' Rust blocks: edit those, not this",
        "//! file. Compiled only: a block that stops compiling fails `cargo check --all-targets`.",
        "#![allow(dead_code, unused_imports, unused_variables, unused_mut)]",
        "",
        "use dspk::ops::{Pipeline, PipelineStage, SpatialWhitening, SurfaceLaplacian};",
        "",
        "type Result = std::result::Result<(), Box<dyn std::error::Error>>;",
        "",
    ]
    count = 0
    for page in PAGES:
        text = (DOCS / page).read_text()
        for i, block in enumerate(re.findall(r"```rust\n(.*?)```", text, re.S)):
            name = re.sub(r"[^a-z0-9]+", "_", Path(page).stem.lower()).strip("_")
            body = "".join(f"    {line}\n" if line else "\n" for line in block.rstrip().split("\n"))
            whole = "let client" in block
            out += [f"/// `{page}`, block {i + 1}.", f"fn {name}_{i + 1}() -> Result {{", (PRELUDE.rstrip("\n") if not whole else "") , body.rstrip("\n"), "    Ok(())", "}", ""]
            count += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(line for line in out) .rstrip() + "\n")
    print(f"rust snippets: {count} blocks")


if __name__ == "__main__":
    main()
