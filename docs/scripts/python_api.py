# ---------- Text ----------

TYPE_PREFIXES = re.compile(r"\b(?:builtins|typing|collections\.abc|os|pathlib|numpy\.typing)\.")


def _strip_optional(t: str) -> str:
    """``Optional[X]`` as ``X | None`` (brackets balanced)."""
    while (i := t.find("Optional[")) != -1:
        depth, j = 0, i + len("Optional[")
        for j in range(i + len("Optional["), len(t)):
            depth += {"[": 1, "]": -1}.get(t[j], 0)
            if depth < 0:
                break
        t = t[:i] + t[i + len("Optional[") : j] + " | None" + t[j + 1 :]
    return t


def doc_type(annotation) -> str:
    """A docstring's type as written: ``{"a", "b"}`` (quoted values) as the set of choices,
    ``dict, str or os.PathLike`` (parsed as a tuple) back as text."""
    elements = getattr(annotation, "elements", None)
    if elements is None:
        return str(annotation)
    items = [str(e) for e in elements]
    if all(i[:1] in "'\"" for i in items):
        return "{" + ", ".join('"' + i.strip("'\"") + '"' for i in items) + "}"
    return ", ".join(items)


def type_text(annotation) -> str:
    if annotation is None:
        return ""
    t = TYPE_PREFIXES.sub("", str(annotation))
    t = t.replace("numpy.", "np.")
    return _strip_optional(t)


ROLE = re.compile(r":(?:func|class|meth|data|attr|mod|obj):`~?([^`]+)`")
RST_CODE = re.compile(r"``([^`]+)``")


class Linker:
    """Turns ``:func:`name``` roles into links to the anchors the generated pages define."""

    def __init__(self) -> None:
        self.anchors: dict[str, str] = {}  # "dspk.ops.filter.sos" and "sos" → url

    def add(self, page: Page, name: str) -> None:
        url = f"/dsp-kitchen/{page.folder}/{page.slug}/#{anchor(name)}"
        self.anchors[f"{page.module}.{name}"] = url
        self.anchors.setdefault(name, url)

    def role(self, target: str, module: str) -> str:
        same_module = target.startswith(module + ".")
        short = target.rsplit(".", 1)[-1] if same_module or not target.startswith("dspk.") else target.removeprefix("dspk.")
        for key in (target, f"{module}.{target}", short):
            if key in self.anchors:
                return f"[`{short}`]({self.anchors[key]})"
        return f"`{short}`"


#: Labels of literal blocks that become tabs (``JSON::`` then ``TOML::``), and their languages.
TAB_LABELS = {"json": "json", "toml": "toml", "python": "python", "rust": "rust", "shell": "sh"}


def _language(label: str, code: str) -> str:
    """A code block's language: from its label, or guessed from its first line."""
    if label.lower() in TAB_LABELS:
        return TAB_LABELS[label.lower()]
    first = code.lstrip().splitlines()[0] if code.strip() else ""
    if first.startswith(("{", "[[")) or first.startswith('"'):
        return "json"
    if re.match(r"^\[[\w.]+\]$", first) or re.match(r"^\w+ = ", first):
        return "toml"
    return "python"


def literal_blocks(text: str) -> list[tuple[str, str]]:
    """Splits docstring text into ("text", ...), ("code", lang, code) and ("tabs", [(label, lang,
    code)]) pieces: reStructuredText literal blocks (a paragraph ending ``::`` or a
    ``.. code-block:: lang`` line, then an indented block). Consecutive blocks introduced by a
    bare label (``JSON::``, ``TOML::``) become one group of tabs."""
    lines = text.split("\n")
    out, buf, i = [], [], 0
    while i < len(lines):
        line = lines[i]
        directive = re.match(r"^\s*\.\. code-block::\s*(\w+)\s*$", line)
        if line.rstrip().endswith("::") or directive:
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            block = []
            while j < len(lines) and (not lines[j].strip() or lines[j].startswith((" ", "\t"))):
                block.append(lines[j])
                j += 1
            if block:
                while block and not block[-1].strip():
                    block.pop()
                code = textwrap.dedent("\n".join(block))
                if directive:
                    label, intro = "", ""
                    lang = directive.group(1)
                else:
                    intro = line.rstrip()[:-2].rstrip()
                    label = intro if intro.lower() in TAB_LABELS else ""
                    lang = _language(label, code)
                if label:
                    if buf:
                        out.append(("text", "\n".join(buf)))
                        buf = []
                    if out and out[-1][0] == "tabs":
                        out[-1][1].append((label, lang, code))
                    else:
                        out.append(("tabs", [(label, lang, code)]))
                else:
                    if intro:
                        buf.append(intro + ":")
                    out.append(("text", "\n".join(buf)))
                    buf = []
                    out.append(("code", lang, code))
                i = j
                continue
        buf.append(line)
        i += 1
    if buf:
        out.append(("text", "\n".join(buf)))
    return out


def _inline(text: str, module: str, linker: Linker) -> str:
    """Prose as MDX: ``code`` → `code`, roles → links; ``<``, ``{`` and ``}`` escaped outside code
    (MDX reads them as JSX)."""
    text = RST_CODE.sub(lambda m: f"`{m.group(1)}`", text)
    text = ROLE.sub(lambda m: linker.role(m.group(1), module), text)
    parts = re.split(r"(`[^`\n]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;").replace("{", "\\{").replace("}", "\\}") for p in parts)


def fence(lang: str, code: str) -> str:
    return f"```{lang}\n{code}\n```"


def markdown(text: str, module: str, linker: Linker) -> str:
    """A docstring's text (reStructuredText-ish or Markdown) as MDX: prose converted, literal
    blocks fenced with their language (so they are highlighted), labelled blocks as tabs."""
    pieces = []
    for piece in literal_blocks(text):
        if piece[0] == "text":
            pieces.append(_inline(piece[1], module, linker))
        elif piece[0] == "code":
            pieces.append("\n" + fence(piece[1], piece[2]) + "\n")
        else:
            tabs = ["", '<Tabs syncKey="format">']
            for label, lang, code in piece[1]:
                tabs += [f'<TabItem label="{label}">', "", fence(lang, code), "", "</TabItem>"]
            tabs += ["</Tabs>", ""]
            pieces.append("\n".join(tabs))
    return "\n".join(pieces)


def cell(text: str) -> str:
    """Text for a table cell: one line, pipes escaped."""
    return " ".join(text.split()).replace("|", "\\|")


def anchor(name: str) -> str:
    """The id Astro gives a heading of ``name`` (github-slugger: lower case, punctuation other
    than ``-`` and ``_`` dropped)."""
    return re.sub(r"[^a-z0-9 _-]", "", name.lower()).replace(" ", "-")


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    m = re.search(r"^(.+?[.:])(\s|$)", text)
    return (m.group(1) if m else text).rstrip(":") + ("" if (m and m.group(1).endswith(".")) else ".")


# ---------- Objects ----------


def resolve(obj):
    """What a public name stands for: an alias's target, or the native object a re-export
    (``Recording = _io.Recording``) assigns."""
    try:
        if obj.is_alias:
            obj = obj.final_target
    except (griffe.AliasResolutionError, griffe.CyclicAliasError):
        return obj
    value = getattr(obj, "value", None)
    path = getattr(value, "canonical_path", None)
    if obj.is_attribute and path and path.startswith("dspk._native"):
        try:
            return obj.modules_collection[path]
        except KeyError:
            return obj
    return obj


def sections(obj):
    if not obj.docstring:
        return []
    return obj.docstring.parse("numpy")


def signature(name: str, obj, *, skip_self: bool = False) -> str:
    params = []
    star_done = False
    for p in obj.parameters:
        if skip_self and p.name in ("self", "cls"):
            continue
        kind = p.kind.value if p.kind else ""
        if kind == "keyword-only" and not star_done:
            params.append("*")
            star_done = True
        prefix = {"variadic positional": "*", "variadic keyword": "**"}.get(kind, "")
        if prefix == "*":
            star_done = True
        s = prefix + p.name
        if p.annotation is not None:
            s += f": {type_text(p.annotation)}"
        if p.default is not None:
            s += f" = {p.default}" if p.annotation is not None else f"={p.default}"
        params.append(s)
    ret = f" -> {type_text(obj.returns)}" if getattr(obj, "returns", None) is not None else ""
    one_line = f"{name}({', '.join(params)}){ret}"
    if len(one_line) <= SIGNATURE_WIDTH:
        return one_line
    inner = "".join(f"    {p},\n" for p in params)
    return f"{name}(\n{inner}){ret}"


NUMBER = re.compile(r"-?\d+\.\d+(?:e-?\d+)?|-?\d+e-?\d+")


def _f32(x: float) -> float:
    return struct.unpack("f", struct.pack("f", x))[0]


def tidy_numbers(text: str) -> str:
    """Floats written as the shortest decimal with the same float32 value: a float32 constant
    reaches Python as its float64 expansion (``1e-6`` as ``9.999999974752427e-07``)."""

    def short(m):
        v = float(m.group(0))
        if len(m.group(0)) < 10 or _f32(v) != v:
            return m.group(0)
        for digits in range(1, 10):
            s = f"{v:.{digits}g}"
            if _f32(float(s)) == v:
                return s if ("." in s or "e" in s) else s + ".0"
        return m.group(0)

    return NUMBER.sub(short, text)


def constant_values(pkg) -> dict[str, str]:
    """Values of the native constants the stubs state (``NAME: int = 4``), by name."""
    out: dict[str, str] = {}

    def walk(mod):
        for name, m in mod.members.items():
            if m.is_alias:
                continue
            if m.is_module:
                walk(m)
            elif m.is_attribute and name.isupper() and m.value is not None:
                out.setdefault(name, tidy_numbers(str(m.value)))

    walk(pkg["_native"])
    return out


def default_text(default, values: dict[str, str]) -> str:
    if default is None:
        return ""
    d = str(default)
    if d in values:
        return f"`{d}` ({values[d]})"
    return f"`{d}`"


# ---------- Rendering ----------


def render_parameters(obj, doc_sections, module: str, linker: Linker, values, *, skip_self=False) -> list[str]:
    documented = {}
    for s in doc_sections:
        if s.kind.value == "parameters":
            for p in s.value:
                documented[p.name] = p
    params = [p for p in obj.parameters if not (skip_self and p.name in ("self", "cls"))]
    items = []
    for p in params:
        d = documented.get(p.name)
        ann = doc_type(d.annotation) if d and d.annotation is not None else type_text(p.annotation)
        # numpy's layout: name, type and default on one line, the description under it
        line = f"- **`{p.name}`**"
        if ann:
            line += f" : `{ann}`"
        if p.default is not None:
            line += f", default {default_text(p.default, values)}"
        if d and d.description:
            line += "  \n  " + markdown(" ".join(d.description.split()), module, linker)
        items.append(line)
    if not items:
        return []
    return ["**Parameters**", "", *items, ""]


def render_doc(doc_sections, module: str, linker: Linker, *, level: int) -> list[str]:
    out = []
    for s in doc_sections:
        kind = s.kind.value
        if kind == "text":
            out += [markdown(s.value, module, linker), ""]
        elif kind == "returns":
            out += ["**Returns**", ""]
            for r in s.value:
                ann = f"`{type_text(r.annotation)}`" if r.annotation else ""
                out.append(f"- {ann}{' — ' if ann and r.description else ''}{markdown(cell(r.description), module, linker)}")
            out.append("")
        elif kind == "raises":
            out += ["**Raises**", ""]
            for r in s.value:
                out.append(f"- `{type_text(r.annotation)}`: {markdown(cell(r.description), module, linker)}")
            out.append("")
        elif kind == "examples":
            out += ["**Examples**", ""]
            for k, v in s.value:
                # doctest directives (``# doctest: +SKIP`` on examples that need a real file)
                # are for the test run, not the reader
                shown = re.sub(r"\s*# doctest:[^\n]*", "", v)
                out += ([f"```python\n{shown}\n```"] if k.value == "examples" else [markdown(v, module, linker)]) + [""]
        elif kind == "admonition":
            out += [f"**{s.title}**", "", markdown(s.value.description, module, linker), ""]
    return out


def render_function(name: str, obj, module, linker, values, *, level=3, owner=None, skip_self=False) -> list[str]:
    shown = f"{owner}.{name}" if owner else name
    doc = sections(obj)
    out = [f"{'#' * level} `{shown}`", "", "```python", signature(name, obj, skip_self=skip_self), "```", ""]
    text = [s for s in doc if s.kind.value == "text"]
    rest = [s for s in doc if s.kind.value not in ("text", "parameters")]
    out += render_doc(text, module, linker, level=level)
    out += render_parameters(obj, doc, module, linker, values, skip_self=skip_self)
    out += render_doc(rest, module, linker, level=level)
    return out


def render_class(name: str, obj, module, linker, values) -> list[str]:
    out = [f"### `{name}`", ""]
    members = obj.all_members  # a subclass of a native class shows what it inherits
    init = members.get("__init__") or members.get("__new__")
    # A wrapper built by its classmethods (``Whitening(native)``) has no public constructor.
    if init is not None and init.is_function and [p.name for p in init.parameters if p.name not in ("self", "cls")] == ["native"]:
        init = None
    if init is not None and init.is_function:
        out += ["```python", signature(name, init, skip_self=True), "```", ""]
    doc = sections(obj)
    out += render_doc([s for s in doc if s.kind.value != "parameters"], module, linker, level=4)
    if init is not None and init.is_function:
        out += render_parameters(init, doc + sections(init), module, linker, values, skip_self=True)
    props, methods = [], []
    for mname, m in members.items():
        if mname.startswith("_"):
            continue
        m = resolve(m)
        if "property" in m.labels or m.is_attribute:
            props.append((mname, m))
        elif m.is_function:
            methods.append((mname, m))
    if props:
        out += ["**Properties**", "", "| Name | Type | Description |", "|---|---|---|"]
        for mname, m in props:
            ann = type_text(getattr(m, "returns", None) if m.is_function else m.annotation)
            text = markdown(cell(m.docstring.value), module, linker) if m.docstring else ""
            out.append(f"| `{mname}` | {f'`{cell(ann)}`' if ann else ''} | {text} |")
        out.append("")
    for mname, m in methods:
        out += render_function(mname, m, module, linker, values, level=4, owner=name, skip_self=True)
    return out


def public_names(mod) -> list[str]:
    if mod.exports is not None:
        return [str(e) for e in mod.exports]
    return [n for n, m in mod.members.items() if not n.startswith("_") and not m.is_module]


def render_page(page: Page, order: int, pkg, linker: Linker, values) -> str:
    mod = pkg[page.module.removeprefix("dspk.")]
    doc = sections(mod)
    intro = doc[0].value if doc and doc[0].kind.value == "text" else ""
    functions, classes, constants = [], [], []
    for name in public_names(mod):
        obj = mod.members.get(name)
        if obj is None:
            continue
        obj = resolve(obj)
        if obj.is_module:
            continue
        (classes if obj.is_class else functions if obj.is_function else constants).append((name, obj))
    lines = [
        "---",
        f'title: "{page.module}"',
        f'description: "{cell(RST_CODE.sub(lambda m: m.group(1), ROLE.sub(lambda m: m.group(1), first_sentence(intro)))).replace(chr(34), chr(39))}"' if intro else f'description: "{page.module}"',
        "editUrl: false",
        "sidebar:",
        f'  label: "{page.label}"',
        f"  order: {order}",
        "---",
        "",
        IMPORTS,
        "",
        GENERATED,
        "",
    ]
    if intro:
        lines += [markdown(intro, page.module, linker), ""]
    summary = [(n, o) for n, o in functions + classes]
    if summary:
        lines += ["| | |", "|---|---|"]
        for name, obj in summary:
            doc = sections(obj)
            text = doc[0].value if doc and doc[0].kind.value == "text" else ""
            lines.append(f"| [`{name}`](#{anchor(name)}) | {markdown(cell(first_sentence(text)), page.module, linker) if text else ''} |")
        lines.append("")
    if functions:
        lines += ["## Functions", ""]
        for name, obj in functions:
            lines += render_function(name, obj, page.module, linker, values)
    if classes:
        lines += ["## Classes", ""]
        for name, obj in classes:
            lines += render_class(name, obj, page.module, linker, values)
    if constants:
        lines += ["## Constants", "", "| Name | Type | Value | Description |", "|---|---|---|---|"]
        for name, obj in constants:
            value = values.get(name) or (str(obj.value) if getattr(obj, "value", None) is not None and not str(obj.value).startswith("_") else "")
            text = markdown(cell(obj.docstring.value), page.module, linker) if obj.docstring else ""
            lines.append(f"| <a id=\"{anchor(name)}\"></a>`{name}` | {f'`{type_text(obj.annotation)}`' if obj.annotation else ''} | {f'`{cell(value)}`' if value else ''} | {text} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_index(folder: str, title: str, intro: str, pkg) -> str:
    """A folder's first page: its modules, each with what it is for."""
    rows = []
    for page in (p for p in PAGES if p.folder == folder):
        doc = sections(pkg[page.module.removeprefix("dspk.")])
        text = doc[0].value if doc and doc[0].kind.value == "text" else ""
        desc = RST_CODE.sub(lambda m: f"`{m.group(1)}`", ROLE.sub(lambda m: f"`{m.group(1)}`", first_sentence(text))) if text else ""
        rows.append(f"| [`{page.module}`](/dsp-kitchen/{folder}/{page.slug}/) | {cell(desc)} |")
    return "\n".join([
        "---", f'title: "{title}"', f'description: "{intro}"', "editUrl: false", "sidebar:", "  label: Overview", "  order: 0", "---", "",
        GENERATED.replace("{/*", "<!--").replace("*/}", "-->"), "", intro, "", "| Module | What it is for |", "|---|---|", *rows, "",
    ])


INDEXES = [
    (CORE, "Python API", "The dspk package, module by module: what each function takes and returns."),
    (SYNAPSE, "Python API", "The dspk.synapse modules, one page each: what each function takes and returns."),
]


def main() -> None:
    pkg = griffe.load("dspk", search_paths=[str(PACKAGE_DIR)], allow_inspection=False, docstring_parser="numpy")
    values = constant_values(pkg)
    linker = Linker()
    for page in PAGES:
        linker.anchors[page.module] = f"/dsp-kitchen/{page.folder}/{page.slug}/"  # :mod: links
        mod = pkg[page.module.removeprefix("dspk.")]
        for name in public_names(mod):
            linker.add(page, name)
    written = 0
    for order, page in enumerate(PAGES, start=1):
        out = DOCS / page.folder / f"{page.slug}.mdx"
        out.parent.mkdir(parents=True, exist_ok=True)
        (DOCS / page.folder / f"{page.slug}.md").unlink(missing_ok=True)  # the generator's older output
        out.write_text(render_page(page, order, pkg, linker, values))
        written += 1
    for folder, title, intro in INDEXES:
        (DOCS / folder / "index.md").write_text(render_index(folder, title, intro, pkg))
    print(f"python_api: {written} pages, {len(values)} constant values from the stubs", file=sys.stderr)


if __name__ == "__main__":
    main()
