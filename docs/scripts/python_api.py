"""The Python API reference, generated from the package's source and stubs (never imported, so no
build of the native module is needed). One page per module, numpy-style: each function's
signature, then its parameters (type, default, description), returns, raises and examples.

Core modules go to ``src/content/docs/reference/python/``, a plugin's to
``src/content/docs/plugins/<plugin>/reference/python/``. Run from the repository root:

    uv run --no-project --with griffe==2.4.1 python -I docs/scripts/python_api.py

Docstrings are read as numpy style (``Parameters`` / ``Returns`` / ``Raises`` / ``Examples``
sections); a docstring without sections still gets a parameter table from the signature.
"""

