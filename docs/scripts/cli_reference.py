"""The command-line and pipeline-spec references, generated from the programs themselves.

- `src/content/docs/reference/cli/<command>.md`: every `dspk` command, from its `--help`.
- `src/content/docs/plugins/synapse/reference/settings/<sorter>.md`: every sorter setting, from
  `dspk-cli-sorter <sorter> --help`.
- `src/content/docs/reference/schemas/*.md` and `public/schemas/pipeline.schema.json`: the pipeline
  spec, from `dspk spec schema`.

Needs both programs built (run from the repository root, standard library only):

    cargo build --profile validate -p dspk-cli --bin dspk -p dspk-cli-sorter --bin dspk-cli-sorter
    python3 docs/scripts/cli_reference.py
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "src" / "content" / "docs"
DSPK = ROOT / "target" / "validate" / "dspk"
SORTER = ROOT / "target" / "validate" / "dspk-cli-sorter"
GENERATED = "<!-- Generated by docs/scripts/cli_reference.py from the programs themselves: edit those, not this page. -->"
#: Options every command has; listed once, on the CLI's first page.
GLOBAL = {"--runtime", "--verbose", "--help", "--version"}
SORTERS = {
    "kilosort4": "Kilosort4",
    "emusort": "EMUsort",
    "mountainsort5": "MountainSort 5",
    "spykingcircus2": "SpyKING CIRCUS 2",
    "tridesclous2": "Tridesclous 2",
}


def help_text(program: Path, *args: str) -> str:
    done = subprocess.run([str(program), *args, "--help"], capture_output=True, text=True, check=True)
    return done.stdout


def sections(text: str) -> tuple[str, str, dict[str, list[str]]]:
    """(description, usage, {section title: lines}) of a clap help text."""
    lines = text.rstrip().split("\n")
    head: list[str] = []
    i = 0
    while i < len(lines) and not lines[i].startswith("Usage:"):
        head.append(lines[i])
        i += 1
    usage = lines[i].removeprefix("Usage:").strip()
    found: dict[str, list[str]] = {}
    current = None
    for line in lines[i + 1 :]:
        m = re.match(r"^([A-Z][A-Za-z ]*):\s*$", line)
        if m:
            current = m.group(1)
            found[current] = []
        elif current:
            found[current].append(line)
    return "\n".join(head).strip(), usage, found


def inline(text: str) -> str:
    """Prose for Markdown: `<` escaped outside code."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;") for p in parts)


#: An entry starts at column 2 (`-x, --long`, `<ARG>`) or 6 (`--long` with no short flag).
ITEM = re.compile(r"^(?: {2}| {6})(?P<head>(?:-\S|--\S|<|\[).*?)(?:\s{2,}(?P<rest>\S.*))?$")


def items(lines: list[str]) -> list[dict]:
    """The entries of an Options / Arguments section, short or long clap layout."""
    out: list[dict] = []
    for line in lines:
        m = ITEM.match(line)
        if m:
            out.append({"head": m.group("head").rstrip(), "text": [m.group("rest")] if m.group("rest") else []})
        elif out:
            s = line.strip()
            out[-1]["text"].append(s)
    return out


def render_item(item: dict) -> tuple[str, str] | None:
    """(flag name, Markdown list entry) of one option or argument."""
    head = item["head"]
    joined = "\n".join(item["text"])
    values = []  # `- name: what it means` lines of "Possible values:"
    if "Possible values:" in joined:
        joined, rest = joined.split("Possible values:", 1)
        for line in rest.strip().split("\n"):
            m = re.match(r"^- ([\w.-]+)(?::\s*(.*))?$", line.strip())
            if m:
                values.append((m.group(1), m.group(2) or ""))
    text = " ".join(joined.split())
    default = re.search(r"\[default: ([^\]]*)\]", text)
    env = re.search(r"\[env: ([A-Z_0-9]+)=?[^\]]*\]", text)
    possible = re.search(r"\[possible values: ([^\]]*)\]", text)
    text = re.sub(r"\s*\[(?:default|env|possible values):[^\]]*\]", "", text).strip()
    line = f"- **`{head}`**"
    extras = []
    if default:
        extras.append(f"default `{default.group(1)}`")
    if possible:
        extras.append("one of " + ", ".join(f"`{v.strip()}`" for v in possible.group(1).split(",")))
    if env:
        extras.append(f"env `{env.group(1)}`")
    if extras:
        line += ": " + ", ".join(extras)
    if text:
        line += "  \n  " + inline(text)
    for name, meaning in values:
        line += f"\n  - `{name}`" + (f": {inline(meaning)}" if meaning else "")
    long_flag = re.search(r"--[\w-]+", head)
    return (long_flag.group(0) if long_flag else head), line


def page(title: str, description: str, order: int, label: str | None = None) -> list[str]:
    out = ["---", f'title: "{title}"', f'description: "{description.replace(chr(34), chr(39))}"', "editUrl: false", "sidebar:"]
    if label:
        out.append(f'  label: "{label}"')
    out += [f"  order: {order}", "---", "", GENERATED, ""]
    return out


def first_line(text: str) -> str:
    return text.split("\n")[0].strip()


def render_command(program: Path, name: str, args: list[str], *, keep_global: bool = False) -> tuple[str, list[str]]:
    """The body of a command's page, with its subcommands as sections."""
    desc, usage, found = sections(help_text(program, *args))
    body = [inline(desc), "", "```text", usage, "```", ""]
    for title in ("Arguments", "Options"):
        entries = [render_item(i) for i in items(found.get(title, []))]
        entries = [e for e in entries if e and (keep_global or e[0] not in GLOBAL)]
        if entries:
            body += [f"**{title}**", "", *[e[1] for e in entries], ""]
    subs = [(m.group(1), m.group(2)) for line in found.get("Commands", []) if (m := re.match(r"^  ([\w-]+)\s+(.*)$", line)) and m.group(1) != "help"]
    for sub, _ in subs:
        sub_desc, sub_body = render_command(program, f"{name} {sub}", [*args, sub])
        body += [f"## `{name} {sub}`", "", *sub_body]
    return first_line(desc), body


def write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n")


def cli() -> None:
    desc, usage, found = sections(help_text(DSPK))
    commands = [(m.group(1), m.group(2)) for line in found["Commands"] if (m := re.match(r"^  ([\w-]+)\s+(.*)$", line)) and m.group(1) != "help"]
    folder = DOCS / "reference" / "cli"
    old = DOCS / "reference" / "cli.md"
    if old.exists():
        old.unlink()
    index = page("CLI", "Every dspk command and flag, generated from the program.", 0, "Overview")
    index += [inline(desc), "", "```text", usage, "```", "", "| Command | What it does |", "|---|---|"]
    for name, text in commands:
        index.append(f"| [`{name}`](/dsp-kitchen/reference/cli/{name}/) | {inline(text).replace('|', chr(92) + '|')} |")
    entries = [render_item(i) for i in items(found.get("Options", []))]
    index += ["", "## Options of every command", "", *[e[1] for e in entries if e], ""]
    write(folder / "index.md", index)
    for order, (name, text) in enumerate(commands, start=1):
        _, body = render_command(DSPK, f"dspk {name}", [name], keep_global=name == "serve")
        write(folder / f"{name}.md", page(f"dspk {name}", text, order, name) + body)
    print(f"cli: {len(commands)} commands")


def sorter_settings() -> None:
    folder = DOCS / "plugins" / "synapse" / "reference" / "settings"
    for order, (name, title) in enumerate(SORTERS.items(), start=1):
        desc, usage, found = sections(help_text(SORTER, name))
        entries = [render_item(i) for i in items(found.get("Options", []))]
        args = [render_item(i) for i in items(found.get("Arguments", []))]
        lines = page(f"{title} settings", f"Every setting of {title} and its default, from the program.", order, title)
        lines += [inline(desc), "", "```text", usage.replace("dspk-cli-sorter", "dspk sort", 1), "```", ""]
        if args:
            lines += ["**Arguments**", "", *[e[1] for e in args if e], ""]
        lines += ["**Settings**", "", *[e[1] for e in entries if e and e[0] not in GLOBAL], ""]
        write(folder / f"{name}.md", lines)
    print(f"sorter settings: {len(SORTERS)} sorters")


# ---------- pipeline spec ----------


def type_of(prop: dict, defs: dict) -> str:
    if "$ref" in prop:
        name = prop["$ref"].rsplit("/", 1)[-1]
        target = defs.get(name, {})
        enums = enum_values(target)
        return " \\| ".join(f'`"{v}"`' for v in enums) if enums else f"[`{name}`](#{name.lower()})"
    if "const" in prop:
        return f'`"{prop["const"]}"`'
    if "anyOf" in prop or "oneOf" in prop:
        options = [o for o in prop.get("anyOf", prop.get("oneOf")) if o.get("type") != "null"]
        return " or ".join(type_of(o, defs) for o in options)
    if "enum" in prop:
        return " \\| ".join(f'`"{v}"`' if v is not None else "`null`" for v in prop["enum"])
    t = prop.get("type", "any")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), "any")
    if t == "array":
        if isinstance(prop.get("items"), dict):
            return f"list of {type_of(prop['items'], defs)}"
        return "list"
    return f"`{t}`"


def enum_values(schema: dict) -> list[str]:
    if "enum" in schema:
        return [str(v) for v in schema["enum"]]
    if "oneOf" in schema and all("const" in o or "enum" in o for o in schema["oneOf"]):
        return [str(o.get("const", o.get("enum", [""])[0])) for o in schema["oneOf"]]
    return []


def description_text(schema: dict) -> str:
    text = " ".join(schema.get("description", "").split())
    text = re.sub(r"\[`([^`]*)`\]", r"`\1`", text)
    return inline(text).replace("|", "\\|")


def fields(schema: dict, defs: dict, *, skip: tuple[str, ...] = ()) -> list[str]:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    rows = [(n, p) for n, p in props.items() if n not in skip]
    if not rows:
        return []
    out = ["| Field | Type | Required | Description |", "|---|---|---|---|"]
    for name, prop in rows:
        default = f" Default: `{json.dumps(prop['default'])}`." if "default" in prop and prop["default"] is not None else ""
        out.append(f"| `{name}` | {type_of(prop, defs)} | {'yes' if name in required else ''} | {description_text(prop)}{default} |")
    return out + [""]


def spec_pages() -> None:
    text = subprocess.run([str(DSPK), "spec", "schema"], capture_output=True, text=True, check=True).stdout
    public = ROOT / "docs" / "public" / "schemas"
    public.mkdir(parents=True, exist_ok=True)
    (public / "pipeline.schema.json").write_text(text)
    schema = json.loads(text)
    defs = schema["$defs"]
    folder = DOCS / "reference" / "schemas"
    old = DOCS / "reference" / "schemas.md"
    if old.exists():
        old.unlink()
    lines = page("Pipeline spec", "Every field of a pipeline spec, generated from its JSON Schema.", 1)
    lines += [description_text(schema), "", "Download the schema for your editor or validator: [pipeline.schema.json](/dsp-kitchen/schemas/pipeline.schema.json).", "", "## The spec", ""]
    lines += fields(schema, defs)
    lines += ["## Nodes", "", "A node's `op` says what it is. `read` and `write` are the ends; the others process.", ""]
    for node in defs["Node"]["oneOf"]:
        op = node["properties"]["op"].get("const") or node["properties"]["op"]["enum"][0]
        lines += [f"### `{op}`", "", description_text(node), ""]
        lines += fields(node, defs, skip=("op",))
    for name, sub in defs.items():
        if name == "Node" or enum_values(sub):
            continue
        lines += [f"## {name}", "", description_text(sub), ""]
        if "oneOf" in sub or "anyOf" in sub:
            for option in sub.get("oneOf", sub.get("anyOf")):
                lines += ["- " + (description_text(option) or type_of(option, defs))]
                lines += [""] + fields(option, defs)
        else:
            lines += fields(sub, defs)
    write(folder / "pipeline.md", lines)
    print(f"spec: {len(defs['Node']['oneOf'])} ops")


def main() -> None:
    cli()
    sorter_settings()
    spec_pages()


if __name__ == "__main__":
    main()
