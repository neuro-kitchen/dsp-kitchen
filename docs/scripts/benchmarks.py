"""The Validation page of dspk against scipy, generated from the committed benchmark records
(`benchmarks/signal-operations/results/scipy_timing-<runtime>.json`). Run from the repository root
(standard library only): python3 docs/scripts/benchmarks.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "benchmarks" / "signal-operations" / "results"
OUT = ROOT / "docs" / "src" / "content" / "docs" / "validation" / "scipy.md"
RUNTIMES = ("cuda", "wgpu", "cpu")


def zarr_codecs() -> None:
    """The Zarr codec page, from `results/zarr_codecs.json`."""
    record = json.loads((RESULTS / "zarr_codecs.json").read_text())
    cases = {c["name"]: c for c in record["cases"]}
    signals = list(dict.fromkeys(n.split(" / ")[0] for n in cases))
    codecs = list(dict.fromkeys(n.split(" / ")[1] for n in cases))
    version = record["dspk"]["version"]
    lines = [
        "---",
        "title: Zarr codecs",
        'description: "Size against speed of each Zarr codec on float32 Neuropixels data."',
        "editUrl: false",
        "sidebar:",
        "  order: 4",
        "---",
        "",
        "<!-- Generated by docs/scripts/benchmarks.py from benchmarks/signal-operations/results/zarr_codecs.json: re-run the benchmark, not this page. -->",
        "",
        f"Measured on {record['date']} with dspk {version}, on {record['machine']}.",
        "",
        "10 s of 384 Neuropixels channels, float32 in µV, default chunking, the median of 3 runs. Reads come from the page cache "
        "(the store was just written), so they measure decompression and not the disk. The machine was also running the app. "
        "Every store read back exactly what was written.",
        "",
    ]
    for signal in signals:
        lines += [f"## {signal.capitalize()}", "", "| Codec | Size (MiB) | Ratio | Write (s) | Read (s) |", "|---|---|---|---|---|"]
        for codec in codecs:
            c = cases[f"{signal} / {codec}"]
            lines.append(f"| {codec} | {c['extra']['size_bytes'] / 2**20:.0f} | {c['extra']['ratio']:.2f} | {c['dspk_ms'] / 1e3:.1f} | {c['extra']['read_ms'] / 1e3:.2f} |")
        lines.append("")
    lines += [
        "## What this means",
        "",
        "- **Raw recordings compress well; filtered ones barely do.** A raw recording is integer steps scaled to µV, so its float32 "
        "values repeat. A filter turns them into full-precision floats, whose low bits look random to every codec here.",
        "- **On filtered data the codec hardly matters.** Every codec saves 7 to 8% in about the same time, so the default costs nothing.",
        "- **`zstd` level 3 is the default** because on raw data it nearly matches level 9's size at about half the write time.",
        "- **`parallel` matters most where compression does the work.** Chunks are compressed on separate threads, which is why several "
        "chunks per processing window speed up writing; on raw data one thread is clearly slower.",
        "",
        "## Run it yourself",
        "",
        "```sh",
        "uv run python benchmarks/signal-operations/zarr_codecs.py",
        "```",
        "",
    ]
    (OUT.parent / "zarr-codecs.md").write_text("\n".join(lines))


def main() -> None:
    records = {r: json.loads((RESULTS / f"scipy_timing-{r}.json").read_text()) for r in RUNTIMES}
    first = records["cuda"]
    version = first["dspk"]["version"] if isinstance(first["dspk"], dict) else first["dspk"]
    names = [c["name"] for c in first["cases"]]
    cases = {r: {c["name"]: c for c in d["cases"]} for r, d in records.items()}
    lines = [
        "---",
        "title: Against SciPy",
        'description: "Every signal operation compared with SciPy and NumPy: time and agreement."',
        "editUrl: false",
        "sidebar:",
        "  order: 1",
        "---",
        "",
        "<!-- Generated by docs/scripts/benchmarks.py from the committed benchmark records: re-run the benchmark, not this page. -->",
        "",
        f"Measured on {first['date']} with dspk {version}, on {first['machine']}.",
        "",
        first["notes"],
        "",
        "## Time (ms)",
        "",
        "| Operation | CUDA | wgpu | CPU runtime | SciPy / NumPy |",
        "|---|---|---|---|---|",
    ]
    for n in names:
        row = [f"{cases[r][n]['dspk_ms']:.0f}" for r in RUNTIMES]
        lines.append(f"| {n} | {row[0]} | {row[1]} | {row[2]} | {cases['cuda'][n]['reference_ms']:.0f} |")
    lines += [
        "",
        "Most of each dspk time is the 92 MB transfer to the device and back. Chaining stages in a "
        "[pipeline](/dsp-kitchen/operations/pipelines/) pays for that transfer once.",
        "",
        "## Agreement (largest difference, relative to SciPy's peak)",
        "",
        "| Operation | CUDA | wgpu | CPU runtime | Tolerance | Passed |",
        "|---|---|---|---|---|---|",
    ]
    for n in names:
        row = [f"{cases[r][n]['rel_err']:.1e}" for r in RUNTIMES]
        ok = all(cases[r][n]["pass"] for r in RUNTIMES)
        lines.append(f"| {n} | {row[0]} | {row[1]} | {row[2]} | {cases['cuda'][n]['tolerance']:.0e} | {'yes' if ok else 'no'} |")
    lines += [
        "",
        "dspk works in float32 on the device, and SciPy in float64, so filters agree to float32 level. Median and common median reference are exact.",
        "",
        "![Time of each operation on CUDA against SciPy](/dsp-kitchen/benchmarks/scipy_timing-cuda.png)",
        "",
        "![Agreement with SciPy on CUDA](/dsp-kitchen/benchmarks/scipy_agreement-cuda.png)",
        "",
        "## Run it yourself",
        "",
        "```sh",
        "uv run python benchmarks/signal-operations/scipy_timing.py --repeats 5",
        "```",
        "",
        "Build with `maturin develop --release` first, and run each benchmark in a fresh process.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    zarr_codecs()
    print(f"validation: {len(names)} operations on {len(RUNTIMES)} runtimes (dspk {version})")


if __name__ == "__main__":
    main()
