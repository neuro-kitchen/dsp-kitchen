"""The Course pages, generated from the playground's `# %%` scripts: their prose, their code, and
the figure each one commits (the plotting cell is replaced by the figure). Chapters 01-07 go to
Learn, 08-09 to the Synapse plugin. Writes `src/data/course.json` for the sidebar.

Run from the repository root (standard library only):

    python3 docs/scripts/course.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLAYGROUND = ROOT / "playground"
DOCS = ROOT / "docs" / "src" / "content" / "docs"
GENERATED = "<!-- Generated by docs/scripts/course.py from the playground script: edit that, not this page. -->"
REPO = "https://github.com/neuro-kitchen/dsp-kitchen/blob/main"
CORE = "learn/course"
SYNAPSE = "plugins/synapse/learn/course"
CHAPTERS = {
    "01_basics": ("Basics", CORE),
    "02_filtering": ("Filtering", CORE),
    "03_referencing": ("Referencing", CORE),
    "04_resampling": ("Resampling", CORE),
    "05_spatial": ("Spatial", CORE),
    "06_pipelines": ("Pipelines", CORE),
    "07_channels": ("Channels", CORE),
    "08_detection": ("Detection", SYNAPSE),
    "09_sorting": ("Sorting", SYNAPSE),
}
#: Local helpers and setup that say nothing about dspk, dropped when the rest of the code doesn't use them.
OPTIONAL_IMPORTS = {
    r"^from pathlib import Path$": "Path",
    r"^import plating$": "plating",
    r"^import tempfile$": "tempfile",
    r"^import time$": "time",
}


def cells(text: str) -> list[tuple[str, str, list[str]]]:
    """(kind, title, lines) of each `# %%` cell."""
    out: list[tuple[str, str, list[str]]] = []
    for line in text.split("\n"):
        m = re.match(r"^# %%\s*(\[markdown\])?\s*(.*)$", line)
        if m:
            out.append(("markdown" if m.group(1) else "code", m.group(2).strip(), []))
        elif out:
            out[-1][2].append(line)
    return out


def prose(lines: list[str]) -> str:
    text = "\n".join(re.sub(r"^# ?", "", line) for line in lines).strip()
    parts = re.split(r"(`[^`\n]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;") for p in parts)


def tidy(code: str, whole: str) -> str:
    """The cell without the setup lines the page doesn't need."""
    kept = []
    for line in code.split("\n"):
        if re.match(r"^FIG = ", line):
            continue
        drop = False
        for pattern, name in OPTIONAL_IMPORTS.items():
            if re.match(pattern, line) and not re.search(rf"\b{name}\.|\b{name}\(", whole.replace("plating.save", "")):
                drop = True
        if re.match(r"^from plating import .*figures", line) and "signals" in line:
            line = "from plating import signals"
        elif re.match(r"^from plating import figures\s*$", line):
            drop = True
        if not drop:
            kept.append(line)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(kept)).strip()


def figure_of(code: str) -> tuple[str, str] | None:
    m = re.search(r'FIG / "([^"]+\.png)"', code)
    if not m:
        return None
    title = re.search(r'title="([^"]+)"', code)
    return m.group(1), title.group(1) if title else ""


def convert(script: Path, chapter: str, folder: str, order: int) -> tuple[str, str]:
    text = script.read_text()
    all_cells = cells(text)
    head, intro, body = "", "", []
    no_figures = "\n".join("\n".join(c[2]) for c in all_cells if figure_of("\n".join(c[2])) is None)
    no_figures = re.sub(r"^FIG = .*$", "", no_figures, flags=re.M)
    for kind, title, lines in all_cells:
        joined = "\n".join(lines).strip()
        if kind == "markdown":
            md = prose(lines)
            m = re.match(r"^# .*?[—-]\s*(?:\d+\.\s*)?(.+?)\n(.*)$", md, re.S) or re.match(r"^# .*?[—-]\s*(?:\d+\.\s*)?(.+)$()", md)
            if m and not head:
                head, intro = m.group(1).strip(), m.group(2).strip()
                body.append(intro)
            else:
                body.append(md)
            continue
        fig = figure_of(joined)
        if fig:
            name, caption = fig
            body.append(f"![{caption or head}](/dsp-kitchen/course/{chapter}/{name})")
            if caption:
                body.append(f"*{caption}.*")
            continue
        code = tidy(joined, no_figures)
        if not code:
            continue
        if title:
            body.append(f"**{title}**" if not title.endswith(":") else f"**{title[:-1]}**")
        body.append(f"```python\n{code}\n```")
    rel = script.relative_to(ROOT).as_posix()
    head = head or script.stem
    first = re.split(r"(?<=[.:])\s", " ".join(intro.split()), maxsplit=1)[0] if intro else head
    description = re.sub(r"[`*]", "", first).replace('"', "'")
    lines = [
        "---",
        f'title: "{head}"',
        f'description: "{description}"',
        f"editUrl: https://github.com/neuro-kitchen/dsp-kitchen/edit/main/{rel}",
        "sidebar:",
        f"  order: {order}",
        "---",
        "",
        GENERATED,
        "",
        "\n\n".join(b for b in body if b),
        "",
        f"The whole script is [`{rel}`]({REPO}/{rel}). Run it with `uv run python {rel}`.",
        "",
    ]
    slug = re.sub(r"^\d+_", "", script.stem).replace("_", "-")
    out = DOCS / folder / chapter.split("_", 1)[1] / f"{slug}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    return head, slug


def main() -> None:
    sidebar: dict[str, list[dict]] = {CORE: [], SYNAPSE: []}
    for chapter, (label, folder) in CHAPTERS.items():
        scripts = sorted(p for p in (PLAYGROUND / chapter).glob("[0-9][0-9]_*.py"))
        if not scripts:
            continue
        for order, script in enumerate(scripts, start=1):
            convert(script, chapter, folder, order)
        sidebar[folder].append({"label": label, "directory": f"{folder}/{chapter.split('_', 1)[1]}"})
        print(f"{chapter}: {len(scripts)} pages")
    out = ROOT / "docs" / "src" / "data" / "course.json"
    out.write_text(json.dumps({"core": sidebar[CORE], "synapse": sidebar[SYNAPSE]}, indent=2) + "\n")


if __name__ == "__main__":
    main()
